#!/usr/bin/env python3
"""build_docs.py - generate the human-readable documents from their single sources.

Single source of truth:
  skills/*/references/*.md  -> docs/*.md  (named long-form documents)
  RESEARCH_LEDGER.csv       -> SOURCE_BIBLIOGRAPHY.md
  tests/cases.json          -> TEST_CASES.md

Usage:  python3 scripts/build_docs.py          # (re)write generated files
        python3 scripts/build_docs.py --check  # exit 1 if any generated file is stale
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SK = ROOT / "skills"
HDR = "<!-- GENERATED by scripts/build_docs.py from {src}. Edit the source file, not this copy. -->\n\n"

DOCS = {
    "docs/HOOK_TAXONOMY.md": ["hook-writing/references/taxonomy.md"],
    "docs/CURIOSITY_AND_RETENTION_FRAMEWORK.md": [
        "hook-idea-diagnosis/references/idea-gate.md",
        "hook-idea-diagnosis/references/curiosity-psychology.md",
        "hook-retention/references/retention-architecture.md"],
    "docs/ARABIC_HOOK_WRITING_GUIDE.md": ["hook-writing/references/iraqi-arabic.md"],
    "docs/SCIENTIFIC_ACCURACY_RULES.md": ["hook-scientific-validation/references/accuracy-rules.md"],
    "docs/ANALYTICS_EXPERIMENT_PROTOCOL.md": ["hook-analytics/references/protocol.md"],
    "docs/EVALUATION_RUBRIC.md": ["hook-evaluation/references/rubric.md"],
    "docs/EXAMPLES.md": ["hook-writing/references/examples.md"],
}

NOT_ACCESSED = """## What was NOT accessed (read this before trusting the bibliography)

- **No video was watched.** Creator material was read as text: interview transcripts hosted by third parties, show notes, social-post text, a book-chapter transcript. Timestamps are recorded only where they appear in a transcript that was read (`timestamps_verified = yes`).
- **Official TikTok documentation was not opened.** TikTok metric definitions come from secondary sources and are provisional (S61).
- **Instagram/Meta first-party pages were not opened.** Retention chart and skip rate are known through press articles that quote Instagram (S10).
- **YouTube Help pages** (S01-S03) were read as page excerpts through a search/fetch tool, not in a browser; some were truncated.
- **Peer-reviewed papers**: most were read at abstract or partial-text level; none were read cover to cover. `access_status` says which.
- **Deliberately not used:** leaked internal documents attributed to MrBeast's production company (not first-party education and of uncertain provenance); copyrighted course transcripts.
- **Alex Hormozi:** only the author-narrated book chapter transcript (S48) was read; his video lectures were not watched. **Film Booth** (S49-S51, S58) and **Colin & Samir** (S53, S55-S57): interview transcripts/snippets only.
- Some links were returned by a search tool and the page body was a snippet; those rows say `search_snippet`.
- Findings that came from prior knowledge rather than the retrieved text are labelled in the row (e.g. S27).
"""

GROUPS = [
    ("Platform documentation (YouTube, Instagram, TikTok)", {"official_platform_doc", "official_blog", "first_party_creator_video"}),
    ("Platform news and secondary platform analysis", {"secondary_analysis", "community"}),
    ("Peer-reviewed research and meta-analyses", {"peer_reviewed", "meta_analysis"}),
    ("Professional bodies and standards (AAO, AOA, ISO, ICO)", {"professional_body", "standards_body"}),
    ("Creator education (interviews, transcripts, posts, book chapter)", {"creator_interview_transcript", "creator_social_post", "book_transcript"}),
]


def read(p):
    return (ROOT / p).read_text(encoding="utf-8")


def build_docs():
    out = {}
    for dest, srcs in DOCS.items():
        body = "\n\n---\n\n".join((SK / s).read_text(encoding="utf-8") for s in srcs)
        out[dest] = HDR.format(src=", ".join("skills/" + s for s in srcs)) + body
    return out


def build_bibliography():
    rows = list(csv.DictReader((ROOT / "RESEARCH_LEDGER.csv").open(encoding="utf-8", newline="")))
    lines = [HDR.format(src="RESEARCH_LEDGER.csv"),
             "# Source bibliography\n",
             f"{len(rows)} sources, accessed 2026-10-20 unless a row says otherwise. Full extraction columns (concept, evidence, application, limits, confidence, module) are in `RESEARCH_LEDGER.csv`. "
             "`Access` is what was actually opened; it is never upgraded.\n",
             NOT_ACCESSED]
    used = set()
    for title, types in GROUPS:
        sel = [r for r in rows if r["source_type"] in types]
        used |= {r["source_id"] for r in sel}
        lines.append(f"\n## {title}\n")
        lines.append("| ID | Source | Author | Date | Access | Class | URL |\n|---|---|---|---|---|---|---|")
        for r in sel:
            t = r["title"].replace("|", "/")
            lines.append(f"| {r['source_id']} | {t} | {r['author'].replace('|','/')} | {r['publication_date'] or 'n/a'} | {r['access_status']} | {r['evidence_class']} | <{r['url']}> |")
    rest = [r for r in rows if r["source_id"] not in used]
    if rest:
        lines.append("\n## Other\n")
        for r in rest:
            lines.append(f"- {r['source_id']} {r['title']} <{r['url']}> ({r['access_status']})")
    lines.append("\n## Disagreements and tensions recorded\n"
                 "- Give away the answer early? Lawrence (S51) says no; spoiler research (S27) found no harm in stories; later work suggests format matters (S63, title only). Treated as a hypothesis to test.\n"
                 "- Retention targets: MrBeast cites ~70% (S53) vs Lawrence 'no magic number, beat your own best' (S58) vs platform: no published benchmark (S01, S06). Package follows own-baseline.\n"
                 "- Broaden vs stay niche: Galloway's core/casual/new fit (S52) vs Colin & Samir caution that mega-channel advice may not transfer to niche audiences (S56).\n"
                 "- Fear appeals: effective on average in meta-analyses (S28, S29) vs this package's accuracy/ethics rule. The prohibition is ethical, not tactical.\n"
                 "- Redundant on-screen text: Mayer's redundancy principle (S23) vs captions benefit (S25). Resolved as key-phrase text, not transcripts [Likely].\n"
                 "- Optometry vs ophthalmology scope: AAO (S36, S38) vs AOA (S37) disagree; package does not adjudicate.\n")
    return "\n".join(lines) + "\n"


def build_cases():
    d = json.loads(read("tests/cases.json"))
    cs = d["cases"]
    L = [HDR.format(src="tests/cases.json"), "# Test cases\n",
         f"{len(cs)} cases, {sum(1 for c in cs if c['held_out'])} marked held-out (topic/wording not used as an example inside any skill file).\n",
         "> " + d["note"] + "\n",
         "**How they are used.** Cases with an `automated_check` are executed by `tests/run_tests.py` (linter, installer, validator). The rest are behaviour specifications for the model-driven workflow: they are specifications only; eight were dry-run in Phase 1 (`tests/DRY_RUNS.md`) and thirteen briefs were run and reviewed in Phase 2 (`validation/phase2/`), all by the same model - not scored by an independent grader. See `tests/RESULTS.md`.\n"]
    for c in cs:
        L.append(f"\n### {c['id']} - {c['category']}{' (held-out)' if c['held_out'] else ''}\n")
        L.append(f"**Input brief:** {c['input_brief']}\n")
        L.append(f"**Expected behaviour:** {c['expected_behavior']}\n")
        L.append("**Hard failure conditions:**\n" + "\n".join(f"- {x}" for x in c["hard_failures"]) + "\n")
        L.append("**Quality criteria:**\n" + "\n".join(f"- {x}" for x in c["quality_criteria"]) + "\n")
        L.append(f"**Expected output structure:** {c['expected_output_structure']}\n")
        if c.get("automated_check"):
            L.append(f"**Automated check:** `{json.dumps(c['automated_check'], ensure_ascii=False)}`\n")
    return "\n".join(L)


def main(argv):
    targets = build_docs()
    targets["SOURCE_BIBLIOGRAPHY.md"] = build_bibliography()
    targets["TEST_CASES.md"] = build_cases()
    stale = []
    for rel, content in targets.items():
        p = ROOT / rel
        if "--check" in argv:
            if not p.is_file() or p.read_text(encoding="utf-8") != content:
                stale.append(rel)
        else:
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content, encoding="utf-8")
    if "--check" in argv:
        for s in stale:
            print("STALE", s)
        print("docs up to date" if not stale else f"{len(stale)} stale")
        return 1 if stale else 0
    print(f"wrote {len(targets)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
